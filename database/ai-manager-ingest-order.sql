ALTER TABLE ai_inbox ADD COLUMN ingest_sequence bigint GENERATED BY DEFAULT AS IDENTITY;
WITH ordered AS (SELECT event_key,row_number() OVER(ORDER BY received_at,event_key) n FROM ai_inbox)
 UPDATE ai_inbox i SET ingest_sequence=o.n FROM ordered o WHERE o.event_key=i.event_key;
SELECT setval(pg_get_serial_sequence('ai_inbox','ingest_sequence'),coalesce(max(ingest_sequence),0)+1,false) FROM ai_inbox;
CREATE INDEX ai_inbox_processing_order_idx ON ai_inbox(conversation_id,ingest_sequence DESC);
